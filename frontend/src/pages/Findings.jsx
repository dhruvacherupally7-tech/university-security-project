import React, { useState, useEffect } from 'react';
import {
  AlertTriangle,
  ShieldAlert,
  Search,
  Filter,
  RefreshCw,
  Sparkles,
  CheckCircle,
} from 'lucide-react';
import api from '../services/api';
import FindingCard from '../components/FindingCard';
import EventModal from '../components/EventModal';
import AIAlertExplanationModal from '../components/AIAlertExplanationModal';
import RiskScoreBadge from '../components/RiskScoreBadge';
import LoadingState from '../components/LoadingState';
import ErrorState from '../components/ErrorState';
import EmptyState from '../components/EmptyState';

export default function Findings() {
  const [findings, setFindings] = useState([]);
  const [summary, setSummary] = useState({ high: 0, medium: 0, low: 0 });
  const [averageRisk, setAverageRisk] = useState(0);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  // Filters
  const [severity, setSeverity] = useState('');
  const [status, setStatus] = useState('');
  const [detectionMethod, setDetectionMethod] = useState('');
  const [category, setCategory] = useState('');
  const [search, setSearch] = useState('');

  const [inspectedEvent, setInspectedEvent] = useState(null);
  const [explanationFindingId, setExplanationFindingId] = useState(null);
  const [isExplanationOpen, setIsExplanationOpen] = useState(false);

  const fetchFindings = async () => {
    try {
      setLoading(true);
      setError(null);
      const res = await api.getFindings({
        severity,
        status,
        detection_method: detectionMethod,
        category,
        search,
      });
      setFindings(res.findings || []);
      setTotal(res.total || 0);
      setSummary(res.summary || { high: 0, medium: 0, low: 0 });
      setAverageRisk(res.average_risk_score || 0);
    } catch (err) {
      console.error('Failed to fetch findings:', err);
      setError(err.message || 'Unable to connect to Security SOC backend.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchFindings();
  }, [severity, status, detectionMethod, category]);

  const handleInspectEvent = async (eventId) => {
    try {
      const ev = await api.getEvent(eventId);
      setInspectedEvent(ev);
    } catch (err) {
      console.error('Could not fetch event:', err);
    }
  };

  return (
    <div className="page-container" style={{ display: 'flex', flexDirection: 'column', gap: '22px' }}>
      {/* Header */}
      <div
        className="glass-card"
        style={{
          padding: '22px 26px',
          display: 'flex',
          justifyContent: 'space-between',
          alignItems: 'center',
          flexWrap: 'wrap',
          gap: '16px',
        }}
      >
        <div>
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '4px', flexWrap: 'wrap' }}>
            <span className="badge-demo" style={{ background: 'rgba(16, 185, 129, 0.15)', borderColor: 'rgba(16, 185, 129, 0.3)', color: '#34d399' }}>
              <Sparkles size={11} /> ACTIVE POSTURE
            </span>
            <span style={{ fontSize: '0.78rem', color: '#94a3b8' }}>
              Active Posture: {summary.high} High • {summary.medium} Medium • {summary.low} Low
            </span>
            {averageRisk > 0 && (
              <span style={{ display: 'inline-flex', alignItems: 'center', gap: '5px', marginLeft: '6px' }}>
                <span style={{ fontSize: '0.72rem', color: '#64748b' }}>Mean Risk:</span>
                <RiskScoreBadge score={averageRisk} size="sm" />
              </span>
            )}
          </div>
          <h1 style={{ fontSize: '1.45rem', fontWeight: 800, color: '#f8fafc' }}>
            Threat Findings
          </h1>
          <p style={{ fontSize: '0.85rem', color: '#64748b' }}>
            Defensive threat correlation findings generated by rule engine logic and behavioral alerts
          </p>
        </div>

        <button onClick={fetchFindings} className="btn btn-secondary">
          <RefreshCw size={15} />
          <span>Refresh Findings</span>
        </button>
      </div>

      {/* Summary KPI Strip */}
      <div
        style={{
          display: 'grid',
          gridTemplateColumns: 'repeat(auto-fit, minmax(210px, 1fr))',
          gap: '16px',
        }}
      >
        <div className="glass-card glow-card" style={{ padding: '16px 20px', borderLeft: '4px solid #38bdf8' }}>
          <div style={{ fontSize: '0.74rem', color: '#94a3b8', textTransform: 'uppercase', fontWeight: 600 }}>
            Total Findings
          </div>
          <div style={{ fontSize: '1.7rem', fontWeight: 800, color: '#f8fafc', marginTop: '4px' }}>
            {total}
          </div>
        </div>

        <div className="glass-card glow-card" style={{ padding: '16px 20px', borderLeft: '4px solid #ef4444' }}>
          <div style={{ fontSize: '0.74rem', color: '#fca5a5', textTransform: 'uppercase', fontWeight: 600 }}>
            High Severity
          </div>
          <div style={{ fontSize: '1.7rem', fontWeight: 800, color: '#f87171', marginTop: '4px' }}>
            {summary.high}
          </div>
        </div>

        <div className="glass-card glow-card" style={{ padding: '16px 20px', borderLeft: '4px solid #f59e0b' }}>
          <div style={{ fontSize: '0.74rem', color: '#fcd34d', textTransform: 'uppercase', fontWeight: 600 }}>
            Medium Severity
          </div>
          <div style={{ fontSize: '1.7rem', fontWeight: 800, color: '#fbbf24', marginTop: '4px' }}>
            {summary.medium}
          </div>
        </div>

        <div className="glass-card glow-card" style={{ padding: '16px 20px', borderLeft: '4px solid #10b981' }}>
          <div style={{ fontSize: '0.74rem', color: '#86efac', textTransform: 'uppercase', fontWeight: 600 }}>
            Low Severity
          </div>
          <div style={{ fontSize: '1.7rem', fontWeight: 800, color: '#34d399', marginTop: '4px' }}>
            {summary.low}
          </div>
        </div>
      </div>

      {/* Filter Bar */}
      <div
        className="glass-card"
        style={{
          padding: '16px 20px',
          display: 'flex',
          gap: '12px',
          flexWrap: 'wrap',
          alignItems: 'center',
        }}
      >
        <div style={{ flex: 1, minWidth: '220px', position: 'relative' }}>
          <Search
            size={14}
            color="#64748b"
            style={{ position: 'absolute', left: '12px', top: '50%', transform: 'translateY(-50%)' }}
          />
          <input
            type="text"
            placeholder="Search findings title, evidence, IP..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && fetchFindings()}
            className="input-field"
            style={{ width: '100%', paddingLeft: '34px', fontSize: '0.82rem' }}
          />
        </div>

        <select
          value={severity}
          onChange={(e) => setSeverity(e.target.value)}
          className="input-field"
          style={{ fontSize: '0.8rem' }}
        >
          <option value="">All Severities</option>
          <option value="High">High</option>
          <option value="Medium">Medium</option>
          <option value="Low">Low</option>
        </select>

        <select
          value={status}
          onChange={(e) => setStatus(e.target.value)}
          className="input-field"
          style={{ fontSize: '0.8rem' }}
        >
          <option value="">All Statuses</option>
          <option value="Investigating">Investigating</option>
          <option value="Open">Open</option>
          <option value="Resolved">Resolved</option>
        </select>

        <select
          value={detectionMethod}
          onChange={(e) => setDetectionMethod(e.target.value)}
          className="input-field"
          style={{ fontSize: '0.8rem' }}
        >
          <option value="">All Detection Methods</option>
          <option value="Rule-Based">Rule-Based</option>
          <option value="ML Anomaly">ML Anomaly</option>
        </select>

        {(severity || status || detectionMethod || category || search) && (
          <button
            onClick={() => {
              setSeverity('');
              setStatus('');
              setDetectionMethod('');
              setCategory('');
              setSearch('');
            }}
            className="btn btn-secondary"
            style={{ fontSize: '0.78rem' }}
          >
            Reset
          </button>
        )}
      </div>

      {/* Findings List */}
      <div>
        {loading ? (
          <LoadingState message="Loading threat findings and correlation evidence..." />
        ) : error ? (
          <ErrorState message={error} onRetry={fetchFindings} />
        ) : findings.length === 0 ? (
          <EmptyState
            title="No Threat Findings"
            message={search || severity || status || detectionMethod || category ? "No security findings match the active criteria." : "No threat findings available."}
          />
        ) : (
          findings.map((finding) => (
            <FindingCard
              key={finding.id}
              finding={finding}
              onInspectEvent={handleInspectEvent}
              onExplainFinding={(id) => {
                setExplanationFindingId(id);
                setIsExplanationOpen(true);
              }}
            />
          ))
        )}
      </div>

      {/* Event Details Inspection Modal */}
      {inspectedEvent && (
        <EventModal
          event={inspectedEvent}
          onClose={() => setInspectedEvent(null)}
        />
      )}

      {/* AI Alert Explanation Modal */}
      <AIAlertExplanationModal
        findingId={explanationFindingId}
        isOpen={isExplanationOpen}
        onClose={() => {
          setIsExplanationOpen(false);
          setExplanationFindingId(null);
        }}
      />
    </div>
  );
}
